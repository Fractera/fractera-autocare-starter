"use client"

// МИКРОФОН В ПОЛЕ ОТВЕТА — заказ Ромы 2026-08-25: «нужно добавить микрофончик, который
// позволит делать аудиозапись… мы должны вызывать наш компонент, который позволяет делать
// и отправлять текстовые сообщения, сделанные голосом и оцифрованные с помощью
// искусственного интеллекта».
//
// 🔒 МИКРОФОН ПИШЕТ ТЕКСТ, А НЕ ЗВУКОВОЕ ВЛОЖЕНИЕ, И ЭТО РОВНО ТО, ЧТО ЗАКАЗАНО. Две
// похожие кнопки делают РАЗНОЕ, и путать их нельзя:
//   • скрепка + аудиофайл → в переписке лежит ЗВУК, его слушают плеером;
//   • микрофон → речь превращается в ТЕКСТ и встаёт в поле ввода, где её можно поправить
//     перед отправкой.
// Оператор диктует ответ, потому что так быстрее, — а пациент получает читаемый текст, а
// не голос сотрудника.
//
// 🔒 БЕРЁТСЯ ГОТОВЫЙ ИНСТРУМЕНТ `_tools/voice-input`, а не пишется свой. Он уже умеет
// запись, полоски громкости, счётчик секунд, отказ микрофона и дверь расшифровки
// `/api/transcribe`. Свой был бы хуже ровно в тех местах, которые видны не сразу.
//
// 🔒 РАСШИФРОВКА НЕ ОТПРАВЛЯЕТСЯ САМА — она встаёт в поле. Так устроен инструмент, и это
// правильно: распознавание иногда слышит не то, а здесь цена ошибки — сообщение живому
// человеку, которое уже не отозвать.

import type { RefObject } from "react"
import VoiceInput from "@/_tools/voice-input/client/voice-input.client"
import { usePromptInputController } from "@/components/ai-elements/prompt-input"

export function VoiceButton(
  { lang, disabled, areaRef }: {
    lang: string
    disabled?: boolean
    /** Настоящее поле ввода: инструмент вставляет речь ПО КУРСОРУ, а не в конец. */
    areaRef: RefObject<HTMLTextAreaElement | null>
  },
) {
  // 🔒 ТЕКСТ БЕРЁТСЯ У КОНТРОЛЛЕРА ПОЛЯ, А НЕ У СВОЕГО СОСТОЯНИЯ. `PromptInput` внутри
  // провайдера ведёт значение сам; заведи здесь второе — и набранное руками пропадёт при
  // первой же диктовке, потому что инструмент отдаёт ПОЛНЫЙ новый текст.
  const controller = usePromptInputController()

  return (
    <VoiceInput
        targetRef={areaRef}
        value={controller.textInput.value}
        onChange={(next) => controller.textInput.setInput(next)}
        lang={lang}
      disabled={disabled}
      // 🔒 АДРЕС ДВЕРИ ЗАДАН ЯВНО, И БЕЗ НЕГО ЗАПИСЬ НЕ РАБОТАЛА БЫ. Инструмент по
      // умолчанию берёт СОСЕДА текущего пути: со страницы /ru/messages это дало бы
      // /ru/messages/api/transcribe — дверь, которой нет. Про эту ловушку прямо написано
      // в самом инструменте, и она уже стоила отладки в панели.
      apiUrl="/api/transcribe"
    />
  )
}
