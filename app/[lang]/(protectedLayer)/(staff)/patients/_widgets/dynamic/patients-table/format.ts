// поднимается то, что отвечает на вопрос «как проект делает X вообще»; здесь
// ответ на «как выглядит ЭТА таблица». Соседняя таблица вправе показывать дату
// иначе, и общий помощник эту свободу отнял бы.

/** Дата визита: ISO из базы → человеческая запись. Пусто — вернуть `null`. */
export function visitDate(iso: string | null | undefined): string | null {
  if (!iso) return null
  const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(iso)
  if (!m) return null
  return `${m[3]}.${m[2]}.${m[1]}`
}

/**
 * Деньги — целыми рублями и с неразрывными пробелами в разрядах.
 *
 * 🔒 БЕЗ КОПЕЕК НАМЕРЕННО: суммы в этой колонке — десятки тысяч, и две цифры
 * после запятой на каждой строке съедают ширину, ничего не сообщая.
 */
export function money(value: number | null | undefined): string {
  const n = Number(value) || 0
  return Math.round(n).toString().replace(/\B(?=(\d{3})+(?!\d))/g, "\u00A0")
}

/** Читаемая запись российского номера. Иностранный возвращается как есть. */
export function phone(e164: string | null | undefined): string {
  if (!e164) return ""
  const m = /^\+7(\d{3})(\d{3})(\d{2})(\d{2})$/.exec(e164)
  return m ? `+7 ${m[1]} ${m[2]}-${m[3]}-${m[4]}` : e164
}
