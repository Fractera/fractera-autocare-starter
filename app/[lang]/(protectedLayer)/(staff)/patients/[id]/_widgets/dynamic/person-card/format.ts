// поднимается то, что отвечает на «как проект делает X вообще»; здесь ответ на
// «как выглядит ЭТА карточка». Копия — это изоляция, а не дублирование: карточка
// вправе показать дату иначе, чем строка списка, и общий помощник отнял бы у неё
// эту свободу.

/** ISO из базы → человеческая запись. Пусто — `null`. */
export function humanDate(iso: string | null | undefined): string | null {
  if (!iso) return null
  const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(iso)
  return m ? `${m[3]}.${m[2]}.${m[1]}` : null
}

/** Деньги целыми рублями, разряды неразрывным пробелом. */
export function money(value: number | null | undefined): string {
  return (Math.round(Number(value) || 0)).toString().replace(/\B(?=(\d{3})+(?!\d))/g, "\u00A0")
}

/** Читаемая запись российского номера. Иностранный — как есть. */
export function phone(e164: string | null | undefined): string {
  if (!e164) return ""
  const m = /^\+7(\d{3})(\d{3})(\d{2})(\d{2})$/.exec(e164)
  return m ? `+7 ${m[1]} ${m[2]}-${m[3]}-${m[4]}` : e164
}
