"use client"

import { useEffect, useState } from "react"
import type { CabinetUi } from "../../../_data/ui.i18n"

// ЗАГОЛОВОК КАБИНЕТА, КОТОРЫЙ ЗАВИСИТ ОТ РОЛИ.
//
// 🔒 ОСТРОВОК, А НЕ СЕРВЕРНЫЙ КОМПОНЕНТ. Роль живёт в сессии, а чтение сессии на
// странице (`cookies()`, `headers()`) выводит из предрендера ВЕСЬ защищённый
// слой одной строкой. Поэтому оболочка остаётся статической, а вопрос «кто ты»
// островок задаёт после гидратации — тем же `/api/me`, что и ящик аккаунта.
//
// 🔒 ДО ОТВЕТА ПЕЧАТАЕТСЯ НЕЙТРАЛЬНЫЙ ЗАГОЛОВОК, а не пустота и не «клиент».
// Пустота даёт скачок разметки, а угаданный статус — обещание, которое через
// полсекунды может смениться на другое. «Личный кабинет» верен для обоих.
//
// 🔒 СВОЙ H1 ОСТРОВОК НЕ ПЕЧАТАЕТ. Он отдаёт только ТЕКСТ, а первый заголовок
// рисует примитив шапки — один владелец на всю раскладку заголовка.
export function CabinetTitle({ ui }: { ui: CabinetUi }) {
  const [title, setTitle] = useState(ui.title)

  useEffect(() => {
    let alive = true
    fetch("/api/me", { cache: "no-store" })
      .then(res => (res.ok ? res.json() : null))
      .then((me: { roles?: string[] } | null) => {
        if (!alive) return
        // Клиент компании — это роль `vip_user`, и только она. Все остальные
        // вошедшие — гости: так решил владелец, и «не VIP» здесь буквально.
        setTitle(me?.roles?.includes("vip_user") ? ui.titleClient : ui.titleGuest)
      })
      .catch(() => {
        // Служба не ответила — оставляем нейтральный заголовок. Назвать человека
        // гостем из-за сетевого отказа значило бы соврать о его статусе.
      })
    return () => { alive = false }
  }, [ui])

  return <>{title}</>
}
