// Устройство то же, что у `security-orbit`: сервер печатает статического близнеца и
// отдаёт его сюда `children`; островок подменяет его анимированной версией уже в браузере.
//
// 🔒 ПОЧЕМУ БЛИЗНЕЦ ОБЯЗАТЕЛЕН ИМЕННО ЗДЕСЬ. `Shimmer` рисует буквы ПРОЗРАЧНЫМИ
// (`bg-clip-text text-transparent`), а видимыми их делает фон, обрезанный по форме букв.
// Поставь его прямо в разметку — и до гидратации главный заголовок сайта покрашен в цвет
// подписи, а не темы. Это тот же класс дефекта, против которого написан закон о движении:
// украшение приходит ВМЕСТО содержания, а не поверх него.
//
// 🔒 ОТЛИЧИЕ ОТ ОБРАЗЦА, И ОНО ОСОЗНАННОЕ: там подмена ждёт первого нажатия или входа
// указателя, здесь — происходит сразу после монтирования. Причина не в лени: заголовок не
// является управляющим элементом, его не «активируют», и требовать от человека действия
// ради того, чтобы имя компании ожило, значит не показать это никому. Цена честная —
// библиотека движения грузится на первом экране, поэтому она грузится ЛЕНИВО, отдельным
// куском, и до его приезда на экране стоит тот же близнец (`fallback={children}`).
//
// 🔒 `prefers-reduced-motion` СОБЛЮДАЕТСЯ ЗДЕСЬ, А НЕ ВНУТРИ: человек, попросивший
// систему не двигать картинку, просто остаётся с близнецом. Так правило не зависит от
// того, что умеет чужой компонент.

import { Suspense, lazy, useEffect, useState, type ReactNode } from "react"

const ShimmerTitle = lazy(() => import("./animated.client"))

export function ShimmerSwap({ text, children }: { text: string; children: ReactNode }) {
  const [live, setLive] = useState(false)

  useEffect(() => {
    if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) return
    setLive(true)
  }, [])

  return live ? <Suspense fallback={children}><ShimmerTitle text={text} /></Suspense> : <>{children}</>
}
