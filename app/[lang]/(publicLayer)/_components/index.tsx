import { getAppConfig } from '@/config/app-config'
import { createContentPage } from '@/lib/content/create-content-page'
import { CompanyBadge, ShimmerTitleBlock } from '../_widgets/static/shimmer-title'
import { HomeCta } from '../_widgets/static/shimmer-title/cta'
import { homePage } from '../_data'
import { meta } from '../_data/meta'

// Вход главной страницы — ТА ЖЕ ФАБРИКА, ЧТО У ПОСТА И ПРАВОВЫХ СТРАНИЦ.
//
// 🔒 ЗДЕСЬ ЕДВА НЕ ПОЯВИЛСЯ ВТОРОЙ СТАНДАРТ (шаг 508, поймано владельцем).
// Сначала главная получила свой вход: «у лендинга другая анатомия, крошки и
// ссылка „назад“ ему не нужны». Проверка показала, что это неправда — из
// пятнадцати свойств шаблона четырнадцать уже исчезали сами, когда их не дают, и
// мешали ровно три `required` в нашем же коде. Разной была не анатомия страницы,
// а обязательность трёх свойств; вывод «нужна вторая фабрика» был сделан из
// собственного кода вместо требования.
//
// Цена ошибки, если бы её не заметили: своя фабрика у лендинга, своя у страниц
// подвала, своя у «страниц про то и это» — и правило, добавленное в одну, не
// доезжает до остальных. Ровно так же перед этим разошлись словари.
//
// Хрома главная не даёт: у корня сайта нет уровня выше, крошка «Главная →
// Главная» была бы ложью. Это причина НЕ ДАВАТЬ хром, а не причина заводить
// второй шаблон страницы.
const page = createContentPage({
  resolve: homePage,
  meta,
  // 🔒 ЗАГОЛОВОК ПЕЧАТАЕТ ШАПКА СТРАНИЦЫ, А НЕ ПЕРВЫЙ ЭКРАН.
  // Здесь стояло `titleInBody: true` — потому что H1 рисовала секция `heroSplit`
  // внутри левой колонки. Список блоков опустошён в шаге 7, секции нет, и без
  // шапки главная осталась бы вовсе без заголовка.
  //
  // ✗ Строка исчезла в шаге 7 не по замыслу: скрипт, вырезавший слот `afterHero`,
  // отступил вверх по комментариям и захватил её. Умолчание совпало с намерением,
  // поэтому дефект ничем себя не выдал. Возвращена явно.
  titleInBody: false,
  // 🔒 ЗАГОЛОВОК ГЛАВНОЙ — ПО ЦЕНТРУ (владелец, 2026-08-25). На главной он
  // единственное содержимое страницы: слева он читался бы как начало текста,
  // которого дальше нет.
  align: "center" as const,
  // 🔒 ЗАГОЛОВОК МЕРЦАЕТ, НО НЕ ЦЕНОЙ СОДЕРЖАНИЯ (Рома, 2026-08-25, со ссылкой на
  // `elements.ai-sdk.dev/components/shimmer`). `Shimmer` красит буквы ПРОЗРАЧНЫМИ и
  // показывает их фоном, обрезанным по форме; поставленный прямо в разметку, он оставил бы
  // главный заголовок сайта серым до гидратации и у всех, кто без JavaScript.
  // Поэтому сервер печатает обычный H1, а мерцающая версия подменяет его уже в браузере —
  // конструкция взята у нашего же образца движения `security-orbit`.
  renderTitle: (title: string) => <ShimmerTitleBlock text={title} />,
  // ✗ СНАЧАЛА ЭТО СТОЯЛО В `afterHero`, И ЭТО БЫЛА ОШИБКА (нашёл Рома 2026-08-25 на живой
  // странице). Имя слота обещает «после первого экрана», и я прочёл его как «под
  // заголовком». На деле `PageShell` печатает его ДО содержимого с шапкой: на главной, где
  // H1 рисует ШАПКА, кнопка «Стать клиентом» встала НАД именем продукта.
  //
  // 🔒 ПРИГЛАШЕНИЕ ОТНОСИТСЯ К ПРОЧИТАННОМУ, А НЕ ПРЕДВАРЯЕТ ЕГО — отсюда `afterContent`,
  // под содержимым страницы. Урок шире слота: имя чужого слота — не описание его места,
  // место проверяется по разметке.
  afterContent: (lang: string) => <HomeCta lang={lang} />,
  // 🔒 ПОДПИСЬ АВТОРА НА ГЛАВНОЙ ВЫКЛЮЧЕНА. Имя компании теперь стоит бейджем НАД
  // заголовком, а подпись под ним давала то же слово ДВАЖДЫ на одном экране: «Fractera —
  // Автозабота — Fractera». Заказ был ПЕРЕНЕСТИ имя наверх, а я его добавил, не убрав
  // снизу.
  showAuthor: false,
  // 🔒 ЧЕРТА ПОД ШАПКОЙ ВЫКЛЮЧЕНА: она отделяет заголовок от текста, а текста у главной
  // нет — под заголовком сразу приглашение. Вместе с рамкой кнопки получались ДВЕ линии,
  // отделяющие пустоту от пустоты.
  showDivider: false,
  // 🔒 ИМЯ КОМПАНИИ — БЕЙДЖ НАД ЗАГОЛОВКОМ (Рома, 2026-08-25). Раньше оно стояло ПОД
  // заголовком строкой автора и читалось как подпись «кто это написал»; над заголовком
  // читается как «чей это продукт» — и это правда.
  //
  // Значение берётся из `APP-CONFIG` на СЕРВЕРЕ и на каждый запрос: владелец меняет его в
  // панели без пересборки, и заморозить это на сборке значило бы сломать саму настройку.
  // Пусто — бейджа нет: пустая плашка хуже отсутствующей.
  eyebrow: () => {
    const short = getAppConfig().short_name
    return short ? <CompanyBadge name={short} /> : null
  },
  // Первый экран главной — сетка (секция `heroSplit`): слово слева, иллюстрация
  // справа. Заголовок обязан стоять ВНУТРИ левой колонки, поэтому его печатает
  // секция, а шапка страницы своего H1 не рисует — иначе их окажется два, и в
  // выдаче они спорят между собой. Метаданные и разметку по-прежнему строит
  // фабрика из того же `title`.
  // 🔒 СЛОТ `afterHero` СНЯТ (шаг 7, решение владельца о минимальной заглушке).
  // Здесь стояли ряд блоков `homeLead` и статический виджет `security-orbit`.
  //
  // 🔒 Это ВИДИМОСТЬ, а не удаление: и функция, и папка виджета
  // `_widgets/static/security-orbit` остались на месте нетронутыми и
  // возвращаются на главную одной строкой. Построенное не удаляем.
})

export const generateMetadata = page.generateMetadata
export default page.Page
