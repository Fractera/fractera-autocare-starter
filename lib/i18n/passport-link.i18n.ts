// Подпись кнопки в подвале, ведущей на паспорт проекта.
//
// 🔒 ПОЧЕМУ ПОДПИСЬ ЗДЕСЬ, А НЕ В СЛОВАРЕ САМОЙ СТРАНИЦЫ. Кнопку рисует подвал —
// общий компонент, который ничего не знает о защищённом слое и не имеет права
// тянуть слова из чужой группы прав (`check:protected`, `cross-group-import`).
// Соседний `architecture-link.i18n.ts` стоит здесь по той же причине.
//
// 🔒 ПОЧЕМУ КНОПКА ВООБЩЕ ЕСТЬ, ЕСЛИ СТРАНИЦА ЗАЩИЩЕНА — решение владельца
// 2026-08-24: «кнопка в подвале видна всегда». Закон `use-roles` §6 запрещает
// публичную кнопку, ведущую в ТУПИКОВЫЙ 403; здесь она ведёт в объясняющее окно
// `AccessGate` с путём входа, то есть ровно в тот знак, который закон и называет
// знаком. Обещание сайта не нарушается: отказ объясняет и предлагает вход.
//
// Два языка — включённый набор проекта (`en, ru`); обещание в
// `development-docs/TRANSLATION-DEBT.md`.

export type PassportLinkUi = {
  /** Кнопка в подвале, рядом с настройками cookie, архитектурой и панелью. */
  footer: string
}

const UI: Record<string, PassportLinkUi> = {
  en: { footer: "Passport" },
  ru: { footer: "Паспорт" },
}

export function passportLinkUi(lang: string): PassportLinkUi {
  return UI[lang] ?? UI[lang.slice(0, 2)] ?? UI.en
}
