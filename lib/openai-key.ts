import { readFileSync } from "node:fs"
import { join } from "node:path"
import { integrationKey } from "@/lib/company/keys"

// Ключ OpenAI приложения — ОДНО место чтения на весь проект.
//
// Читался он в трёх маршрутах тремя почти одинаковыми функциями, и это ровно тот
// случай, когда «почти» дороже дубля: одна из копий однажды научится читать новый
// источник, а две другие продолжат отвечать «ключа нет» — и разбираться в этом
// будут по симптому «в одном месте работает, в другом нет».
//
// Порядок источников: КЛЮЧИ АДМИНИСТРАТОРА, затем окружение процесса, затем
// `.env.local` слота. Дальше не ищем — ключ службы RAG принадлежит панели, а не
// приложению клиента.
//
// 🔒 ЭКРАН АДМИНИСТРАТОРА СИЛЬНЕЕ ОКРУЖЕНИЯ (шаг 29), и порядок именно такой не случайно:
// иначе на сервере, где переменная уже задана, поле на экране ничего бы не меняло — то
// есть выглядело бы сломанным, оставаясь исправным. Источник добавлен ЗДЕСЬ, потому что
// этот файл объявлен единственным местом чтения ключа; добавь я его рядом — вернулась бы
// ровно та беда, ради которой файл и заведён.
export function openAiKey(): string {
  const own = integrationKey("OPENAI_API_KEY")
  if (own) return own
  if (process.env.OPENAI_API_KEY) return process.env.OPENAI_API_KEY
  try {
    const raw = readFileSync(join(process.cwd(), ".env.local"), "utf8")
    return (raw.match(/^OPENAI_API_KEY=(.+)$/m) ?? [])[1]?.trim() ?? ""
  } catch {
    return ""
  }
}
