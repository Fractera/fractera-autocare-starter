// Телефон в E.164 — единственная форма, в которой он живёт в базе.
//
// 🔒 НОРМАЛИЗАЦИЯ ОБЯЗАТЕЛЬНА, ПОТОМУ ЧТО НА ТЕЛЕФОНЕ СТОИТ УНИКАЛЬНОСТЬ ЛЮДЕЙ.
// CRM отдаёт номер как его вбил администратор: «8 (928) 123-45-67», «+79281234567»,
// «9281234567». Без приведения к одной форме один и тот же человек трижды пройдёт
// проверку «такого телефона ещё нет» и трижды окажется в базе — а потом трижды
// получит одно и то же сообщение.
//
// Перенесено из `lib/phone.js` исходника без изменений в логике: правила разбора
// российских номеров там верные и оплачены живой базой.

/** Приводит номер к E.164 или возвращает `null`, если это не номер. */
export function normalizePhone(raw: string | null | undefined): string | null {
  if (!raw) return null
  let s = String(raw).replace(/[^\d+]/g, "")
  if (!s) return null

  // Плюс сохраняется только ведущий: «+7 (900) +12» — это не номер с двумя кодами,
  // а мусор, и второй плюс надо выбросить, а не пытаться понять.
  if (s.startsWith("+")) s = "+" + s.slice(1).replace(/\D/g, "")
  else s = s.replace(/\D/g, "")

  if (s.startsWith("+")) {
    // Длина по E.164: от 11 до 16 знаков вместе с плюсом.
    return s.length >= 11 && s.length <= 16 ? s : null
  }
  if (s.length === 11 && (s.startsWith("8") || s.startsWith("7"))) return "+7" + s.slice(1)
  // Мобильный без кода страны: «9281234567».
  if (s.length === 10 && s.startsWith("9")) return "+7" + s
  if (s.length >= 11 && s.length <= 15) return "+" + s
  return null
}

/** Читаемая запись российского номера. Иностранный возвращается как есть. */
export function formatPhone(e164: string | null | undefined): string {
  if (!e164) return ""
  const m = /^\+7(\d{3})(\d{3})(\d{2})(\d{2})$/.exec(e164)
  return m ? `+7 ${m[1]} ${m[2]}-${m[3]}-${m[4]}` : e164
}
